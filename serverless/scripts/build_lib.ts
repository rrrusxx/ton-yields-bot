/**
 * What the build does, without side effects, so tests can check that the
 * committed modules are up to date.
 */

import { deflateSync } from "node:zlib";

/** Telegram refuses a widget over this many bytes after zlib at level 9 */
export const WIDGET_COMPRESSED_LIMIT = 4096;
/** Node's zlib can be a few dozen bytes off Telegram's count: stay well under */
export const WIDGET_COMPRESSED_TARGET = 3800;
/** Telegram refuses a widget over this many bytes of UTF-8 */
export const WIDGET_HTML_LIMIT = 32768;

const HEADER = "// Generated by scripts/build.ts from {source}. Do not edit by hand.\n";

/** Trims every line and drops empty ones (the widget's script ends its statements with semicolons) */
export function minify(html: string): string {
  return html.split("\n").map((l) => l.trim()).filter((l) => l.length > 0).join("\n");
}

export function compressedSize(html: string): number {
  return deflateSync(new TextEncoder().encode(html), { level: 9 }).length;
}

export function widgetModule(source: string): string {
  return HEADER.replace("{source}", "widget/yields.html") + `export const WIDGET_HTML = ${JSON.stringify(minify(source))};\n`;
}

export function dataModule(snapshotJson: string): string {
  const snapshot = JSON.parse(snapshotJson);
  if (typeof snapshot?.date !== "string" || !Array.isArray(snapshot?.rows)) throw new Error("not a post snapshot");
  return HEADER.replace("{source}", "sample/snapshot.json") + `export const SNAPSHOT = ${JSON.stringify(snapshot)};\n`;
}
